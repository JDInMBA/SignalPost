#!/usr/bin/env python3
"""Write the explorer's data payload from a run's envelopes.

The page ships the same run twice, on purpose:

* `viewer/profiles.jsonl` is the machine copy, one envelope per line, which is
  what `jq` and any other reader wants.
* `viewer/profiles.js` is the same records as a classic script that assigns
  `window.SIGNALPOST_PROFILES`.

The duplication buys one thing, and it is the thing the previous viewer got
wrong. A page opened from `file://` cannot `fetch` a file beside it: every
browser treats the page's origin as opaque and refuses the request. The old
viewer's only data path was that fetch, inside a `.catch(() => {})`, so anyone
who double-clicked `index.html` instead of starting a web server saw an empty
shell with no error. A classic `<script src>` is not subject to that rule, so
the payload loads whether the page is served or opened directly.

    ./.venv/bin/python tools/build_viewer.py
    ./.venv/bin/python tools/build_viewer.py --check
"""
from __future__ import annotations

import argparse
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
DEFAULT_SOURCE = ROOT / "out" / "smoke-envelopes.jsonl"
JSONL = ROOT / "viewer" / "profiles.jsonl"
PAYLOAD = ROOT / "viewer" / "profiles.js"

BANNER = """/* Generated by tools/build_viewer.py - do not edit.

   The same records as profiles.jsonl, as a classic script so that the page
   loads them when it is opened from the file system as well as when it is
   served. Regenerate with:

       ./.venv/bin/python tools/build_viewer.py
*/
window.SIGNALPOST_PROFILES = """


def _records(path: pathlib.Path) -> list[dict]:
    return [json.loads(line) for line in path.read_text().splitlines() if line.strip()]


def _render(records: list[dict]) -> str:
    # One record per line keeps the generated file reviewable in a diff: a run
    # that changes one company changes one line.
    lines = ",\n".join(json.dumps(r, ensure_ascii=False, sort_keys=True) for r in records)
    return f"{BANNER}[\n{lines}\n];\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--source", type=pathlib.Path, default=DEFAULT_SOURCE,
                    help="envelopes to publish (default: the committed smoke run)")
    ap.add_argument("--check", action="store_true",
                    help="verify the committed payload matches, and change nothing")
    args = ap.parse_args()

    if args.check:
        if not PAYLOAD.exists():
            print(f"FAIL {PAYLOAD.relative_to(ROOT)} is missing; the page would open empty")
            return 1
        if not JSONL.exists():
            print(f"FAIL {JSONL.relative_to(ROOT)} is missing")
            return 1
        expected = _render(_records(JSONL))
        if PAYLOAD.read_text() != expected:
            print("FAIL viewer/profiles.js does not match viewer/profiles.jsonl; "
                  "run tools/build_viewer.py")
            return 1
        print(f"OK   viewer payload matches profiles.jsonl ({len(_records(JSONL))} companies)")
        return 0

    if not args.source.exists():
        print(f"FAIL {args.source} not found; run the agent first")
        return 1
    records = _records(args.source)
    if not records:
        print(f"FAIL {args.source} is empty")
        return 1

    JSONL.write_text("".join(
        json.dumps(r, ensure_ascii=False, sort_keys=True) + "\n" for r in records))
    PAYLOAD.write_text(_render(records))
    print(f"wrote {JSONL.relative_to(ROOT)} and {PAYLOAD.relative_to(ROOT)} "
          f"({len(records)} companies, {PAYLOAD.stat().st_size // 1024} KiB payload)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
